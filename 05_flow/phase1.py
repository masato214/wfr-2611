def _ack(src):
    """改められた文を根拠に持つ要素に、改めた決定の文を足す（見直し済みの印）"""
    add = []
    queue = list(src)
    while queue:
        x = queue.pop(0)
        for old, new in AMENDS.items():
            if (x == old or ("." not in old and x.startswith(old + "."))) and new not in src and new not in add:
                add.append(new); queue.append(new)   # 改めた文がさらに改められていれば、それも足す
    return src + add


